# Ошибка: "2" + "3" соединяет строки и даёт "23", а не число 5
# Исправление: преобразовать строки в int перед сложением
 
first = "2"
second = "3"
print("Фрагмент А — типы ДО преобразования:", type(first), type(second))
result_a = int(first) + int(second)
print("Фрагмент А — типы ПОСЛЕ преобразования:", type(int(first)), type(int(second)))
print(f"Фрагмент А: {first} + {second} = {result_a}")   # Получаем 5
 
# Ошибка: input() возвращает строку, нельзя прибавить 1 к строке
# Исправление: преобразовать результат input() в int
 
age_raw = input("\nФрагмент Б — Возраст: ")
print("Тип ДО преобразования:", type(age_raw))
age = int(age_raw)
print("Тип ПОСЛЕ преобразования:", type(age))
print(f"Фрагмент Б: возраст через год = {age + 1}")
 
# Ошибка: из-за приоритета операций вычисляется first + second + (third / 3),
# то есть 4 + 7 + 3.333... = 14.333..., а не (4 + 7 + 10) / 3 = 7.0.
# Исправление: заключить сумму в скобки.
 
first = 4
second = 7
third = 10
average = (first + second + third) / 3
print(f"\nФрагмент В: среднее = {average}") # Получаем 7
